// Copies Nathan's steps (the code nodes of the Ask workflow) out of n8n/gen.js into src/nathan/steps.gen.ts,
// word for word, so the API and n8n run the same logic while both exist. Run after changing Nathan in gen.js:
//   node scripts/extract-nathan.cjs
// gen.js runs here with its file writes captured in memory: nothing under n8n/ changes.
const fs = require('fs');
const path = require('path');
const Module = require('module');

const genPath = path.resolve(__dirname, '../../../n8n/gen.js');
const written = {};
const fakeFs = { ...fs, mkdirSync() {}, writeFileSync(p, s) { written[path.basename(p)] = String(s); } };
const m = new Module(genPath, module);
m.filename = genPath;
m.paths = Module._nodeModulePaths(path.dirname(genPath));
const realRequire = m.require.bind(m);
m.require = (id) => (id === 'fs' ? fakeFs : realRequire(id));
const log = console.log; console.log = () => {};
try { m._compile(fs.readFileSync(genPath, 'utf8'), genPath); } finally { console.log = log; }

const ask = JSON.parse(written['ask.json']);
const code = ask.nodes.filter((n) => n.type === 'n8n-nodes-base.code');
const out = [
  '// GENERATED by scripts/extract-nathan.cjs from n8n/gen.js (the Ask workflow). Do not edit by hand:',
  '// change Nathan in gen.js, then run `node scripts/extract-nathan.cjs`.',
  '// Each step is the n8n code node verbatim; ask.ts gives it the same $ / $input / $getWorkflowStaticData it has in n8n.',
  '// @ts-nocheck',
  '/* eslint-disable */',
  'export const STEPS = {',
  ...code.map((n) => '  ' + JSON.stringify(n.name) + ': function ($, $input, $getWorkflowStaticData) {\n' + n.parameters.jsCode + '\n  },'),
  '};',
  '',
];
fs.writeFileSync(path.resolve(__dirname, '../src/nathan/steps.gen.ts'), out.join('\n'));
log('steps.gen.ts: ' + code.length + ' steps: ' + code.map((n) => n.name).join(', '));

// The shared prelude every n8n code node starts with (toGame, toPlayer, ...), for the routes that shape rows as n8n does
const src = fs.readFileSync(genPath, 'utf8');
const start = src.indexOf('function prelude() {');
const end = src.indexOf('\n}\n', start);
if (start < 0 || end < 0) throw new Error('prelude() not found in gen.js');
const SHAPERS = ['toGame', 'toPlayer', 'publicPlayer', 'ratingsByPlayerGame', 'toRating'];
fs.writeFileSync(path.resolve(__dirname, '../src/shape.gen.ts'), [
  '// GENERATED by scripts/extract-nathan.cjs from n8n/gen.js (prelude()). Do not edit by hand:',
  '// change it in gen.js, then run `node scripts/extract-nathan.cjs`.',
  '// How n8n turns database rows into what the page reads; the API routes shape their answers with the same code.',
  '// @ts-nocheck',
  '/* eslint-disable */',
  'const shapers = (() => {',
  src.slice(start + 'function prelude() {'.length + 1, end),
  '  return { ' + SHAPERS.join(', ') + ' };',
  '})();',
  ...SHAPERS.map((s) => 'export const ' + s + ': (x: any) => any = shapers.' + s + ';'),
  '',
].join('\n'));
log('shape.gen.ts: ' + SHAPERS.join(', '));
